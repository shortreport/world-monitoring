def setup_ax(ax, ylim, ylabel, fmt="%.1f%%", fs_tick=6.5):
    ax.axvspan(x[4], x[7]+0.5, color="lightblue", alpha=0.22)
    ax.axhline(0, color="gray", lw=0.5, ls="--")
    ax.set_xticks([x[i] for i in xtick_idx])
    ax.set_xticklabels(xtick_label, fontsize=fs_tick)
    ax.yaxis.set_major_formatter(mticker.FormatStrFormatter(fmt))
    ax.set_ylim(*ylim)
    ax.set_ylabel(ylabel, fontsize=7)
    ax.grid(axis="y", lw=0.3, alpha=0.5)
    ax.tick_params(axis="y", labelsize=6.5)

def plot_lines(ax, data, colors):
    for i,(label,vals) in enumerate(data.items()):
        ax.plot(x, vals, marker="o", ms=1.8, lw=1.2,
                color=colors[i % len(colors)], label=label)

def add_legend(ax, ncol=1):
    ax.legend(loc="upper left", fontsize=5.8, framealpha=0.85,
              ncol=ncol, handlelength=1.5, borderpad=0.4, labelspacing=0.3)

def covid_label(ax, ylim):
    ax.text(x[5]+0.1, ylim[0] + (ylim[1]-ylim[0])*0.97,
            "COVID", fontsize=5, color="steelblue", va="top")

